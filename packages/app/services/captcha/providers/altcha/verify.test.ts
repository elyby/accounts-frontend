import * as Sentry from '@sentry/react';

import expect from 'app/test/unexpected';
import { type AltchaChallenge, getAltchaChallenge } from 'app/services/api/captcha';

import verify, { encodePayload, getExpiresAt } from './verify';
import type { WorkerRequest, WorkerResponse } from './altcha.worker';

jest.mock('app/services/api/captcha', () => ({ getAltchaChallenge: jest.fn() }));
jest.mock('@sentry/react', () => ({ metrics: { distribution: jest.fn() } }));

const getChallengeMock = getAltchaChallenge as jest.MockedFunction<typeof getAltchaChallenge>;
const distributionMock = Sentry.metrics.distribution as jest.MockedFunction<typeof Sentry.metrics.distribution>;

/**
 * The recorded metrics as { name: attributes }
 */
function getMetrics() {
    return Object.fromEntries(distributionMock.mock.calls.map(([name, value, options]) => [name, { value, ...options }]));
}

/**
 * There are no Web Workers in jsdom, so the test plays the workers' part
 */
class FakeWorker extends EventTarget {
    static instances: Array<FakeWorker> = [];

    requests: Array<WorkerRequest> = [];
    isTerminated = false;

    constructor() {
        super();
        FakeWorker.instances.push(this);
    }

    postMessage(request: WorkerRequest): void {
        this.requests.push(request);
    }

    terminate(): void {
        this.isTerminated = true;
    }

    respond(response: WorkerResponse): void {
        this.dispatchEvent(new MessageEvent('message', { data: response }));
    }

    fail(message: string): void {
        this.dispatchEvent(Object.assign(new Event('error'), { message }));
    }
}

/**
 * Generated by altcha-lib 2.6.0 (JS) with the secrets of the backend's AltchaTest.php and verified by the backend's
 * library: cost 10, counter 50, counterMax 100. The keys are in the order, in which the backend emits them (sorted)
 */
const CHALLENGE: AltchaChallenge = {
    parameters: {
        algorithm: 'PBKDF2/SHA-256',
        cost: 10,
        data: {
            counterMax: 100,
        },
        expiresAt: 4102444800,
        keyLength: 32,
        keyPrefix: '5b8f3627d377b1a63e3b5741c27a05dc',
        keySignature: '6cce7171e543eac6a9b33fa11d704ce6569810efa9529418e66cff41c652c591',
        nonce: 'b46b4afc1167cd29c6be41f2681ada49',
        salt: '198e7a0476ca75badf7bfb574eac0dff',
    },
    signature: '575647068b00ec307ce6552a2497f38e2869638f0f35ccef0fbfee78c4c9bcc4',
};

const SOLUTION = {
    counter: 50,
    derivedKey: '5b8f3627d377b1a63e3b5741c27a05dce52e56caadd10559909dbf93a0ab6601',
    time: 1.3,
};

function decode(token: string) {
    return JSON.parse(atob(token));
}

/**
 * Lets verify() receive the challenge and start the workers
 */
const flush = () => new Promise((resolve) => setTimeout(resolve));

describe('services/captcha/providers/altcha/verify', () => {
    let hardwareConcurrency: PropertyDescriptor | undefined;

    beforeEach(() => {
        distributionMock.mockClear();
        FakeWorker.instances = [];
        // @ts-expect-error the fake implements only the used part of the Worker's interface
        global.Worker = FakeWorker;
        hardwareConcurrency = Object.getOwnPropertyDescriptor(navigator, 'hardwareConcurrency');
        Object.defineProperty(navigator, 'hardwareConcurrency', { value: 2, configurable: true });

        getChallengeMock.mockResolvedValue({
            ...CHALLENGE,
            response: new Response(null, { headers: { Date: 'Fri, 01 Jan 2100 00:00:00 GMT' } }),
        });
    });

    afterEach(() => {
        // @ts-expect-error there is no Worker in jsdom
        delete global.Worker;

        if (hardwareConcurrency) {
            Object.defineProperty(navigator, 'hardwareConcurrency', hardwareConcurrency);
        } else {
            // @ts-expect-error restores the jsdom's own value
            delete navigator.hardwareConcurrency;
        }
    });

    it('should request the challenge, split the work between the workers and return the payload', async () => {
        const result = verify('/api/captcha/altcha/challenge', new AbortController().signal);
        await flush();

        expect(getChallengeMock.mock.calls, 'to satisfy', [['/api/captcha/altcha/challenge']]);
        expect(FakeWorker.instances, 'to have length', 2);
        expect(FakeWorker.instances[0].requests, 'to satisfy', [
            { challenge: CHALLENGE, counterMode: 'uint32', counterStart: 0, counterStep: 2 },
        ]);
        expect(FakeWorker.instances[1].requests, 'to satisfy', [{ counterStart: 1, counterStep: 2 }]);

        FakeWorker.instances[1].respond({ type: 'solution', solution: SOLUTION });

        const { token } = await result;
        expect(decode(token), 'to equal', { challenge: CHALLENGE, solution: SOLUTION });
        expect(FakeWorker.instances, 'to have items satisfying', { isTerminated: true });
    });

    it('should report the total progress of all the workers', async () => {
        getChallengeMock.mockResolvedValue({
            ...CHALLENGE,
            parameters: { ...CHALLENGE.parameters, data: { counterMax: 99 } },
            response: new Response(),
        });
        const onProgress = jest.fn();
        const result = verify('/challenge', new AbortController().signal, onProgress);
        await flush();

        const [first, second] = FakeWorker.instances;
        first.respond({ type: 'progress', checked: 10 });
        second.respond({ type: 'progress', checked: 12 });
        first.respond({ type: 'progress', checked: 20 });
        // The workers may check a bit more values than the limit, but the end is reached only with the solution
        second.respond({ type: 'progress', checked: 90 });
        second.respond({ type: 'solution', solution: SOLUTION });
        // The late messages are ignored
        first.respond({ type: 'progress', checked: 30 });

        await result;
        expect(onProgress.mock.calls, 'to satisfy', [[0.1], [0.22], [0.32], [0.99]]);
    });

    it('should not pass the response object into the challenge', async () => {
        const result = verify('/challenge', new AbortController().signal);
        await flush();

        expect(FakeWorker.instances[0].requests[0].challenge, 'not to have key', 'response');

        FakeWorker.instances[0].respond({ type: 'solution', solution: SOLUTION });

        expect(decode((await result).token).challenge, 'not to have key', 'response');
    });

    it('should not create workers for the algorithms, which are not bundled', async () => {
        getChallengeMock.mockResolvedValue({
            ...CHALLENGE,
            parameters: { ...CHALLENGE.parameters, algorithm: 'ARGON2ID' },
            response: new Response(),
        });

        await expect(verify('/challenge', new AbortController().signal), 'to be rejected with', /Unsupported ALTCHA algorithm: ARGON2ID/);
        expect(FakeWorker.instances, 'to be empty');
    });

    it('should wait for the rest of the workers, when one of them is out of time', async () => {
        const result = verify('/challenge', new AbortController().signal);
        await flush();

        FakeWorker.instances[0].respond({ type: 'solution', solution: null });
        FakeWorker.instances[1].respond({ type: 'solution', solution: SOLUTION });

        expect(decode((await result).token).solution, 'to equal', SOLUTION);
    });

    it('should reject when the challenge was not solved in time', async () => {
        const result = verify('/challenge', new AbortController().signal);
        await flush();

        FakeWorker.instances.forEach((worker) => worker.respond({ type: 'solution', solution: null }));

        await expect(result, 'to be rejected with', /in time/);
    });

    it('should reject when a worker fails', async () => {
        const result = verify('/challenge', new AbortController().signal);
        await flush();

        FakeWorker.instances[0].fail('Out of memory');

        await expect(result, 'to be rejected with', /Out of memory/);
        expect(FakeWorker.instances, 'to have items satisfying', { isTerminated: true });
    });

    it('should stop the workers when aborted', async () => {
        const controller = new AbortController();
        const result = verify('/challenge', controller.signal);
        await flush();

        controller.abort();

        await expect(result, 'to be rejected with', expect.it('to have property', 'name', 'AbortError'));
        expect(FakeWorker.instances, 'to have items satisfying', { isTerminated: true });
    });

    describe('metrics', () => {
        it('should report the solving time and the hash rate', async () => {
            // The solving's start and finish
            const now = jest.spyOn(performance, 'now').mockReturnValueOnce(100).mockReturnValueOnce(1100);
            const result = verify('/challenge', new AbortController().signal);
            await flush();

            FakeWorker.instances[0].respond({ type: 'progress', checked: 10 });
            FakeWorker.instances[1].respond({ type: 'solution', solution: SOLUTION });
            await result;
            now.mockRestore();

            const attributes = {
                'altcha.outcome': 'solved',
                'altcha.algorithm': 'PBKDF2/SHA-256',
                'altcha.cost': 10,
                'altcha.counter_max': 100,
                'altcha.hash_rate_bucket': 32,
                'device.cores': 2,
                'page.hidden': false,
            };

            expect(getMetrics(), 'to exhaustively satisfy', {
                // All the 51 values up to the solution are counted, not the lagging progress
                'altcha.hash_rate': { value: 51, attributes },
                'altcha.solve_duration': { value: 1000, unit: 'millisecond', attributes },
            });
        });

        it('should report the failure without the hash rate', async () => {
            const result = verify('/challenge', new AbortController().signal);
            await flush();

            FakeWorker.instances.forEach((worker) => worker.respond({ type: 'solution', solution: null }));
            await expect(result, 'to be rejected');

            expect(getMetrics(), 'to only have keys', ['altcha.solve_duration']);
            expect(getMetrics(), 'to satisfy', { 'altcha.solve_duration': { attributes: { 'altcha.outcome': 'error' } } });
        });

        it('should report the abort', async () => {
            const controller = new AbortController();
            const result = verify('/challenge', controller.signal);
            await flush();

            controller.abort();
            await expect(result, 'to be rejected');

            expect(getMetrics(), 'to satisfy', { 'altcha.solve_duration': { attributes: { 'altcha.outcome': 'aborted' } } });
        });

        it('should mark the measurement, when the page was hidden during the solving', async () => {
            const visibilityState = jest.spyOn(document, 'visibilityState', 'get');
            const result = verify('/challenge', new AbortController().signal);
            await flush();

            visibilityState.mockReturnValue('hidden');
            document.dispatchEvent(new Event('visibilitychange'));
            visibilityState.mockRestore();
            document.dispatchEvent(new Event('visibilitychange'));

            FakeWorker.instances[0].respond({ type: 'solution', solution: SOLUTION });
            await result;

            expect(getMetrics(), 'to satisfy', { 'altcha.solve_duration': { attributes: { 'page.hidden': true } } });
        });
    });

    describe('#encodePayload', () => {
        it('should produce exactly the payload, accepted by the backend', () => {
            // The payload of the CHALLENGE and the SOLUTION, which the backend's library accepts
            const goldenPayload =
                'eyJjaGFsbGVuZ2UiOnsicGFyYW1ldGVycyI6eyJhbGdvcml0aG0iOiJQQktERjIvU0hBLTI1NiIsImNvc3QiOjEwLCJkYXRhIjp7ImNvdW50ZXJNYXgiOjEwMH0sImV4cGlyZXNBdCI6NDEwMjQ0NDgwMCwia2V5TGVuZ3RoIjozMiwia2V5UHJlZml4IjoiNWI4ZjM2MjdkMzc3YjFhNjNlM2I1NzQxYzI3YTA1ZGMiLCJrZXlTaWduYXR1cmUiOiI2Y2NlNzE3MWU1NDNlYWM2YTliMzNmYTExZDcwNGNlNjU2OTgxMGVmYTk1Mjk0MThlNjZjZmY0MWM2NTJjNTkxIiwibm9uY2UiOiJiNDZiNGFmYzExNjdjZDI5YzZiZTQxZjI2ODFhZGE0OSIsInNhbHQiOiIxOThlN2EwNDc2Y2E3NWJhZGY3YmZiNTc0ZWFjMGRmZiJ9LCJzaWduYXR1cmUiOiI1NzU2NDcwNjhiMDBlYzMwN2NlNjU1MmEyNDk3ZjM4ZTI4Njk2MzhmMGYzNWNjZWYwZmJmZWU3OGM0YzliY2M0In0sInNvbHV0aW9uIjp7ImNvdW50ZXIiOjUwLCJkZXJpdmVkS2V5IjoiNWI4ZjM2MjdkMzc3YjFhNjNlM2I1NzQxYzI3YTA1ZGNlNTJlNTZjYWFkZDEwNTU5OTA5ZGJmOTNhMGFiNjYwMSIsInRpbWUiOjEuM319';

            expect(encodePayload(CHALLENGE, SOLUTION), 'to equal', goldenPayload);
        });
    });

    describe('#getExpiresAt', () => {
        const serverNow = Date.UTC(2100, 0, 1) - 600_000; // 10 minutes before the expiration
        const response = new Response(null, { headers: { Date: new Date(serverNow).toUTCString() } });

        it('should count the lifetime against the server time', () => {
            // The client's clock is 1 hour behind
            const receivedAt = serverNow - 3_600_000;

            expect(getExpiresAt(CHALLENGE, response, receivedAt), 'to equal', receivedAt + 600_000);
        });

        it('should fallback to the client time when there is no Date header', () => {
            const receivedAt = serverNow;

            expect(getExpiresAt(CHALLENGE, new Response(), receivedAt), 'to equal', receivedAt + 600_000);
        });
    });
});
